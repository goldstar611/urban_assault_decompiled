def load_blob_groups(set_bas_path):
    """Parse one SET.BAS blob -> [[kid names group0], [g1], [g2]].

    Group order in the blob: vehicles (visproto.lst), buildings
    (set.sdf lego), ground fillers (slurps). Names come from the NAME
    chunks of each kid OBJT.
    """
    with open(set_bas_path, "rb") as f:
        mc2 = compile.Form().parse_stream(f)[0]
    base = mc2.get_single("BASE")
    if base is None:
        fail("no BASE form in %s" % set_bas_path)
    groups = []
    for gk in base.get_single("KIDS").sub_chunks:
        kids_form = gk.get_single("KIDS")
        names = []
        if kids_form is not None:
            for model in kids_form.sub_chunks:
                nm = [n.name for n in model.get_all("NAME") if n.name]
                names.append(nm[0] if nm else None)
        groups.append(names)
    if len(groups) != 3:
        fail("%s: expected 3 kid groups, got %d" % (set_bas_path, len(groups)))
    for g, names in enumerate(groups):
        if any(n is None for n in names):
            fail("%s: group %d has kids without a NAME chunk" % (set_bas_path, g))
    return groups


def load_blob_pool_names(set_bas_path):
    """Return {'SKLT': [...], 'VANM': [...], 'VBMP': [...]} exact emrs names."""
    with open(set_bas_path, "rb") as f:
        mc2 = compile.Form().parse_stream(f)[0]
    embd = mc2.get_single("EMBD")
    res = defaultdict(list)
    for name, resource in embd.emrs_resources.items():
        res[resource.form_type].append(name)
    return res


