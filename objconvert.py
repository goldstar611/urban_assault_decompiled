#!/usr/bin/env python3
"""SET.BAS -> OBJ working-copy assembly (Task 5, Phase 2).

Takes the OpenUA standalone package, creates a working copy at
~/utmshared/openua-obj/ (movie/audio dirs excluded, per-set SET.BAS
blobs dropped), runs the engine-side ua_export tool per in-scope set
(DATA tree and dataxp tree, SET46/Set46 skipped), and assembles the
exported OBJ per-model assets into the working copy together with
regenerated single-load-chain scripts (visproto.lst, set.sdf,
slurps.lst), RSRCPOOL safety-net copies and the DATA/MC2RES/Skeleton
collision skeletons. Finally validates every set and writes
docs/texture-mapping.md.

Re-runnable: every step only (re)creates the output locations it owns
(per-set OBJECTS/, skeleton/, the three scripts files, RSRCPOOL/,
MC2RES/Skeleton/). Everything else is left untouched.

Usage:
    python3 objconvert.py [--package DIR] [--work DIR] [--export-dir DIR]
                          [--steps copy,export,assemble,validate,doc]
                          [--trees DATA,dataxp] [--sets 1,2]
                          [--no-reuse] [--skip-verify2]
"""

