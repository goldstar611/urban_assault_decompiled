def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--package", default=DEFAULT_PACKAGE)
    ap.add_argument("--work", default=DEFAULT_WORK)
    ap.add_argument("--export-dir", default=DEFAULT_EXPORT)
    ap.add_argument("--steps", default="copy,export,assemble,validate,doc")
    ap.add_argument("--trees", default="DATA,dataxp")
    ap.add_argument("--sets", default="",
                    help="comma separated set numbers, default: all in scope")
    ap.add_argument("--no-reuse", action="store_true",
                    help="re-run ua_export even if the export dir exists")
    ap.add_argument("--skip-verify2", action="store_true")
    args = ap.parse_args()

    steps = [s.strip() for s in args.steps.split(",") if s.strip()]
    trees = [t.strip() for t in args.trees.split(",") if t.strip()]
    only_sets = {int(x) for x in args.sets.split(",") if x.strip()} \
        if args.sets else None

    selected = []
    for tree in trees:
        for setdir, num in find_set_dirs(args.package, tree):
            if only_sets and num not in only_sets:
                continue
            selected.append((tree, setdir, num))
    log("plan: %d sets: %s"
        % (len(selected),
           ", ".join("%s/%s" % (t[0], t[1]) for t in selected)))

    if "copy" in steps:
        copy_work(args.package, args.work)

    infos = []
    for tree, setdir, num in selected:
        tp = tree_paths(args.package, tree, setdir)
        blob = find_blob_path(tp)
        tag = "set%d%s" % (num, "_xp" if tree == "dataxp" else "")
        export_dir = os.path.join(args.export_dir, tag)
        if "export" in steps:
            export_set(args.package, blob, tag, export_dir,
                       args.no_reuse, not args.skip_verify2)
        if "assemble" in steps:
            infos.append(assemble_set(args.package, args.work,
                                      args.export_dir, tree, setdir, num))

    all_ok = True
    if "validate" in steps and infos:
        grand_ok = grand_total = 0
        for info in infos:
            ok, total, errors = validate_set(info)
            grand_ok += ok
            grand_total += total
            head = "VALIDATED %d/%d" % (ok, total)
            if errors:
                all_ok = False
                log("%s FAIL (%s/%s, %s)" % (head, info["tree"],
                                             info["setdir"], info["tag"]))
                for e in errors[:20]:
                    log("  FAIL: %s" % e)
                if len(errors) > 20:
                    log("  ... and %d more" % (len(errors) - 20))
            else:
                log("%s (%s/%s, %s)" % (head, info["tree"], info["setdir"],
                                        info["tag"]))
        log("TOTAL VALIDATED %d/%d" % (grand_ok, grand_total))
        if not all_ok:
            sys.exit(1)

    if "doc" in steps:
        if not infos:
            infos = [describe_set(args.package, args.work, args.export_dir,
                                  tree, setdir, num)
                     for tree, setdir, num in selected]
        build_doc(args.export_dir, infos,
                  os.path.join(REPO, "docs", "texture-mapping.md"))

    log("done")


if __name__ == "__main__":
    main()
