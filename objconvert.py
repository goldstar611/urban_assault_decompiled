def parse_lst_entries(path):
    """(entry names, raw lines) of a visproto/slurps style lst (latin-1)."""
    entries = []
    with open(path, "rb") as f:
        text = f.read().decode("latin-1")
    raw_lines = text.split("\n")
    for line in raw_lines:
        code = re.split(r"[;#\n\r]", line)[0].strip()
        if not code:
            continue
        if code.startswith(">"):
            break
        entries.append(code)
    return entries, raw_lines


def parse_sdf_lego(path):
    """(lego_lines, everything_after) split at the first '>' line."""
    with open(path, "rb") as f:
        text = f.read().decode("latin-1")
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.startswith(">"):
            return lines[:i], lines[i:]
    fail("no '>' section separator in %s" % path)


def extract_comment(line):
    m = re.search(r"[;#]", line)
    return line[m.start():] if m else ""


