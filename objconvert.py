def build_doc(export_root, infos, out_path):
    """Per set: model -> texture files table + shared-atlas audit."""
    lines = []
    lines.append("# Texture mapping per set (SET.BAS -> OBJ conversion)")
    lines.append("")
    lines.append("Computed from the engine export sidecars "
                 "(``<name>.obj.mat.json`` and ``<name>.uattach``) in `%s`."
                 % export_root)
    lines.append("")
    lines.append("Per-model png naming: `<MODEL>_<ORIG>.png`, where ORIG is "
                 "the original texture resource name including its "
                 "extension (e.g. `BAGGER.ILBM` -> "
                 "`VP_PANZ1_BAGGER.ILBM.png`). Materials whose texture has "
                 "no per-model png (animated ANM atlas names and a few "
                 "pool textures) keep the `<ORIG>.png` name in the .mtl "
                 "and resolve via the `<ORIG>.png` copies placed in each "
                 "set's `RSRCPOOL/`.")
    lines.append("")
    for info in infos:
        tag = info["tag"]
        export_dir = info["export_dir"]
        lines.append("## %s (%s/%s)" % (tag, info["tree"], info["setdir"]))
        lines.append("")
        ci = ci_index(os.listdir(export_dir))
        all_kids = info["veh"] + info["bld"] + info["slp"]
        kid_group = {}
        for g, names in enumerate((info["veh"], info["bld"], info["slp"])):
            for n in names:
                kid_group[n] = GROUP_NAMES[g]
        refcount = Counter()
        refgroup = defaultdict(Counter)
        model_tex = {}
        missing_per_model = Counter()
        for name in all_kids:
            if name in info["empty"]:
                continue
            _files, origs, _pairs, _err = model_asset_plan(export_dir, ci, name)
            model_tex[name] = sorted(origs, key=str.lower)
            for t in origs:
                key = t.lower()
                refcount[key] += 1
                refgroup[key][kid_group[name]] += 1
                if not ci_pick(ci, name + "_" + t + ".png"):
                    missing_per_model[key] += 1
        lines.append("### %s: shared-atlas audit (models referencing each "
                     "original texture)" % tag)
        lines.append("")
        lines.append("| orig texture | models | vehicles | buildings | "
                     "slurps | refs without per-model png |")
        lines.append("|---|---|---|---|---|---|")
        for tex, cnt in refcount.most_common(30):
            g = refgroup[tex]
            lines.append("| %s | %d | %d | %d | %d | %d |"
                         % (tex, cnt, g["vehicle"], g["building"],
                            g["slurp"], missing_per_model.get(tex, 0)))
        lines.append("")
        lines.append("Distinct textures referenced: %d; models with meshes: "
                     "%d; empty models: %d."
                     % (len(refcount), len(model_tex), len(info["empty"])))
        lines.append("")
        lines.append("### %s: per-model textures" % tag)
        lines.append("")
        lines.append("| model | group | per-model png files | pool-only "
                     "(ANM atlas) textures |")
        lines.append("|---|---|---|---|")
        for name in all_kids:
            if name not in model_tex:
                lines.append("| %s | %s | (empty model) | |"
                             % (name, kid_group.get(name, "?")))
                continue
            per_model = [t for t in model_tex[name]
                         if ci_pick(ci, name + "_" + t + ".png")]
            pool_only = [t for t in model_tex[name]
                         if not ci_pick(ci, name + "_" + t + ".png")]
            lines.append("| %s | %s | %s | %s |"
                         % (name, kid_group.get(name, "?"),
                            ", ".join(name + "_" + t + ".png"
                                      for t in per_model) or "-",
                            ", ".join(t + ".png" for t in pool_only) or "-"))
        lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    log("doc: wrote %s (%d lines)" % (out_path, len(lines)))


