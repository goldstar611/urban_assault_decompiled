def export_set(package, set_bas_path, tag, export_dir, no_reuse, verify2):
    if os.path.isdir(export_dir) and not no_reuse:
        n = sum(1 for f in os.listdir(export_dir) if f.endswith(".obj"))
        if n > 50:
            log("export %s: reusing existing export (%d files)"
                % (tag, len(os.listdir(export_dir))))
            return
    rel = os.path.relpath(set_bas_path, package).replace(os.sep, "/")
    base_cmd = [
        "podman", "run", "--rm",
        "-v", "%s:/work:Z" % UA_SOURCE,
        "-v", "%s:/gamedata:ro" % package,
        PODMAN_IMAGE, UA_EXPORT_BIN,
        "/gamedata/" + rel,
        "--outdir", "/work/export/" + tag,
    ]
    log("export %s: running ua_export ..." % tag)
    r = subprocess.run(base_cmd, capture_output=True, text=True)
    if r.returncode != 0:
        fail("ua_export failed for %s\n%s\n%s"
             % (tag, r.stdout[-2000:], r.stderr[-2000:]))
    tail = " | ".join(r.stdout.strip().split("\n")[-4:])
    log("export %s: %s" % (tag, tail))
    if verify2:
        r2 = subprocess.run(base_cmd + ["--verify2"], capture_output=True,
                            text=True)
        line = r2.stdout.strip().split("\n")[-1] if r2.stdout.strip() else "no output"
        log("verify2 %s: %s" % (tag, line))
        if r2.returncode != 0:
            fail("verify2 failed for %s" % tag)


