def describe_set(package, work, export_root, tree, setdir, num):
    tag = "set%d%s" % (num, "_xp" if tree == "dataxp" else "")
    export_dir = os.path.join(export_root, tag)
    if not os.path.isdir(export_dir):
        fail("export dir missing for %s: %s" % (tag, export_dir))
    tp = tree_paths(package, tree, setdir)
    blob = find_blob_path(tp)
    groups = load_blob_groups(blob)
    pool_names = load_blob_pool_names(blob)
    veh, bld, slp = groups
    kid_names = veh + bld + slp
    log("scan %s/%s (%s): kids %d = %d vehicles + %d buildings + %d slurps"
        % (tree, setdir, tag, len(kid_names), len(veh), len(bld), len(slp)))
    wset = os.path.join(work, tree, setdir)
    exp_ci = ci_index(os.listdir(export_dir))
    empty = {n for n in kid_names if ci_pick(exp_ci, n + ".EMPTY")}
    return {
        "tag": tag, "tree": tree, "setdir": setdir, "num": num,
        "veh": veh, "bld": bld, "slp": slp,
        "empty": empty,
        "blob": blob,
        "export_dir": export_dir,
        "wobj": os.path.join(wset, tp["objdir"]),
        "wskel": os.path.join(wset, "skeleton"),
        "wscripts": os.path.join(wset, tp["scriptsdir"]),
        "wpool": os.path.join(wset, tp["rsrcpool"]),
        "wmc2res_skeleton": "",
        "vp_name": "visproto.lst", "sdf_name": "SET.SDF",
        "tex_fallback": Counter(),
    }


def assemble_set(package, work, export_root, tree, setdir, num):
    tag = "set%d%s" % (num, "_xp" if tree == "dataxp" else "")
    export_dir = os.path.join(export_root, tag)
    if not os.path.isdir(export_dir):
        fail("export dir missing for %s: %s" % (tag, export_dir))
    tp = tree_paths(package, tree, setdir)
    blob = find_blob_path(tp)
    groups = load_blob_groups(blob)
    pool_names = load_blob_pool_names(blob)
    veh, bld, slp = groups
    kid_names = veh + bld + slp
    log("assemble %s/%s (%s): kids %d = %d vehicles + %d buildings + %d slurps"
        % (tree, setdir, tag, len(kid_names), len(veh), len(bld), len(slp)))

    wset = os.path.join(work, tree, setdir)
    wobj = os.path.join(wset, tp["objdir"])
    wskel = os.path.join(wset, "skeleton")
    wscripts = os.path.join(wset, tp["scriptsdir"])
    wpool = os.path.join(wset, tp["rsrcpool"])
    for d in (wobj, wskel, wpool):
        if os.path.isdir(d):
            shutil.rmtree(d)
        os.makedirs(d)
    os.makedirs(wscripts, exist_ok=True)

    export_files = os.listdir(export_dir)
    ci = ci_index(export_files)

    # ---- pre-pass: authoritative per-model plans ----------------------
    plans = {}
    empty_kids = []
    for name in kid_names:
        if ci_pick(ci, name + ".EMPTY"):
            empty_kids.append(name)
            continue
        files, origs, mat_pairs, errors = model_asset_plan(export_dir, ci, name)
        for e in errors:
            fail("%s kid %s: %s" % (tag, name, e))
        plans[name] = (files, origs, mat_pairs)
    per_model_exact = set()
    for files, _o, _m in plans.values():
        per_model_exact |= files
    pool = split_pool(export_files, per_model_exact)
    log("assemble %s: pool files skl=%d anm=%d png=%d (blob pool: skl=%d "
        "vanm=%d vbmp=%d)"
        % (tag, len(pool.get(".skl", [])), len(pool.get(".anm", [])),
           len(pool.get(".png", [])), len(pool_names.get("SKLT", [])),
           len(pool_names.get("VANM", [])), len(pool_names.get("VBMP", []))))

    # ---- OBJECTS: per-model files ------------------------------------
    tex_fallback = Counter()
    for name, (files, origs, mat_pairs) in plans.items():
        with open(os.path.join(export_dir, ci_pick(ci, name + ".obj")), "r") as f:
            obj_text = f.read()
        with open(os.path.join(wobj, name + ".obj"), "w") as f:
            f.write(re.sub(r"(?mi)^\s*mtllib\s+.*$", "mtllib %s.mtl" % name,
                           obj_text, count=1))
        with open(os.path.join(export_dir, ci_pick(ci, name + ".obj.mtl")),
                  "r") as f:
            mtl_text = f.read()
        mtl_lines = []
        for line in mtl_text.split("\n"):
            m = re.match(r"^(\s*map_Kd\s+)(\S+)(.*)$", line)
            if m:
                tok = m.group(2)
                per_model_png = ci_pick(ci, name + "_" + tok)
                if per_model_png:
                    line = m.group(1) + per_model_png + m.group(3)
                else:
                    tex_fallback[tok] += 1
            mtl_lines.append(line)
        with open(os.path.join(wobj, name + ".mtl"), "w") as f:
            f.write("\n".join(mtl_lines))
        # per-model png cross-check: no per-model copy -> must exist as a
        # pool png (copied to RSRCPOOL), otherwise the model cannot bind it
        for t in sorted(origs):
            if not ci_pick(ci, name + "_" + t + ".png"):
                if not ci_pick(ci, t + ".png"):
                    fail("%s kid %s: texture '%s' has neither a per-model "
                         "png nor a pool png in export" % (tag, name, t))
                tex_fallback[t + ".png"] += 1
        for f in sorted(files - {name + ".obj", name + ".obj.mtl"}):
            src = ci_pick(ci, f)
            shutil.copyfile(os.path.join(export_dir, src),
                            os.path.join(wobj, src))

    for name in empty_kids:
        with open(os.path.join(wobj, name + ".obj"), "w") as f:
            f.write(EMPTY_OBJ_STUB.format(name=name))

    # BEEBOX.BAS stays at its original relative location (DATA sets keep it
    # in scripts/, dataxp sets keep it in Objects/).
    for srcdir, dstdir in ((tp["scriptsdir_path"], wscripts),
                           (tp["objdir_path"], wobj)):
        bee = os.path.join(srcdir, "BEEBOX.BAS")
        if os.path.isfile(bee):
            shutil.copyfile(bee, os.path.join(dstdir, "BEEBOX.BAS"))

    # ---- skeleton/: per-model col2 skeleton copies --------------------
    sdf_path = None
    for cand in os.listdir(tp["scriptsdir_path"]):
        if cand.lower() == "set.sdf":
            sdf_path = os.path.join(tp["scriptsdir_path"], cand)
    if sdf_path is None:
        fail("%s: no SET.SDF in %s" % (tag, tp["scriptsdir_path"]))
    lego_lines, _after = parse_sdf_lego(sdf_path)
    lego_entries = [ln for ln in lego_lines if ln.strip() and not ln.startswith(">")]
    if len(lego_entries) != len(bld):
        fail("%s: set.sdf lego entries %d != building kids %d"
             % (tag, len(lego_entries), len(bld)))
    col2bases = {}
    for kid, line in zip(bld, lego_entries):
        toks = re.split(r"[;#]", line)[0].split()
        if len(toks) < 2 or not toks[0].lower().endswith(".base"):
            fail("%s: unexpected set.sdf lego line: %r" % (tag, line))
        col2base = strip_suffix(os.path.basename(toks[1]), ".sklt")
        col2bases[kid] = col2base
        src = pool_skl_for_base(pool, export_files, col2base)
        if src is None:
            fail("%s: no exported skeleton for col2 base '%s' (kid %s)"
                 % (tag, col2base, kid))
        shutil.copyfile(os.path.join(export_dir, src),
                        os.path.join(wskel, "%s_%s.skl" % (kid, col2base)))

    # ---- scripts/ ------------------------------------------------------
    vp_name = "visproto.lst"
    for cand in os.listdir(tp["scriptsdir_path"]):
        if cand.lower() == "visproto.lst":
            vp_name = cand
    vp_entries, vp_raw = parse_lst_entries(os.path.join(tp["scriptsdir_path"],
                                                        vp_name))
    out = ["; visproto.lst regenerated by objconvert.py",
           "; source: %s/%s/scripts/%s + engine export tag %s"
           % (tree, setdir, vp_name, tag),
           "; one <name>.obj per blob kid (vehicle group, blob order); "
           "original comments kept where names match 1:1"]
    matched = 0
    for i, kid in enumerate(veh):
        sep, comment = " ", ""
        if i < len(vp_entries) and \
                strip_suffix(vp_entries[i], ".base").lower() == \
                strip_suffix(kid + ".base", ".base").lower():
            m = re.match(r"^(\S+)(\s*)([;#].*)$", vp_raw[i])
            if m:
                sep, comment = m.group(2), m.group(3)
            else:
                sep = ""
            matched += 1
        out.append("%s.obj%s%s" % (kid, sep, comment))
    out.append(">")
    with open(os.path.join(wscripts, vp_name), "wb") as f:
        f.write(("\n".join(out) + "\n").encode("latin-1"))
    if matched != len(veh):
        log("assemble %s: visproto comment match only %d/%d (plain names "
            "used elsewhere)" % (tag, matched, len(veh)))

    sdf_out_name = os.path.basename(sdf_path)
    new_lego = []
    bld_i = 0
    for line in lego_lines:
        if not line.strip() or line.startswith(">"):
            new_lego.append(line)
            continue
        code = re.split(r"[;#]", line)[0]
        comment = extract_comment(line)
        kid = bld[bld_i]
        bld_i += 1
        col2base = col2bases[kid]
        rebuilt = re.sub(r"^(\s*)\S+(\s+)\S+(.*)$",
                         lambda m: "%s%s.obj%s skeleton/%s_%s.skl%s"
                         % (m.group(1), kid, m.group(2), kid, col2base,
                            m.group(3)),
                         code, count=1)
        new_lego.append(rebuilt + comment)
    sdf_new = "\n".join(new_lego + _after)
    with open(os.path.join(wscripts, sdf_out_name), "wb") as f:
        f.write(sdf_new.encode("latin-1"))

    slurps = ["; slurps.lst regenerated by objconvert.py",
              "; source: %s/%s OBJECTS/SET.BAS blob ground group (blob "
              "order, 36 horizontal then 36 vertical fillers)" % (tree, setdir)]
    for kid in slp:
        slurps.append("%s.obj" % kid)
    with open(os.path.join(wscripts, "slurps.lst"), "wb") as f:
        f.write(("\n".join(slurps) + "\n").encode("latin-1"))

    # ---- RSRCPOOL: pool ANM (+png) safety net -------------------------
    for f in pool.get(".anm", []):
        shutil.copyfile(os.path.join(export_dir, f), os.path.join(wpool, f))
    for f in pool.get(".png", []):
        shutil.copyfile(os.path.join(export_dir, f), os.path.join(wpool, f))
    # alias copies under the exact original pool names so name-based
    # lookups (e.g. bmpanim rsrc:rsrcpool/<name> resolution) find them
    anm_by_stem = {}
    for f in pool.get(".anm", []):
        anm_by_stem.setdefault(os.path.splitext(f)[0].lower(), f)
    anm_aliases = 0
    for e in pool_names.get("VANM", []):
        stem = strip_suffix(e, ".anm")
        src_name = anm_by_stem.get(stem.lower())
        if not src_name:
            fail("%s: no exported pool ANM for blob VANM name '%s'" % (tag, e))
        src = os.path.join(export_dir, src_name)
        for alias in {e, e if e.lower().endswith(".anm") else e + ".anm"}:
            if alias.lower() == src_name.lower():
                continue
            shutil.copyfile(src, os.path.join(wpool, alias))
            anm_aliases += 1

    # ---- DATA/MC2RES/Skeleton: ColSide / ColCross ----------------------
    mc2res = find_mc2res_dir(os.path.join(work, tree))
    wskl_dir = os.path.join(mc2res, "Skeleton")
    os.makedirs(wskl_dir, exist_ok=True)
    for src, dst in (("colside.skl", "ColSide.skl"),
                     ("colcross.skl", "ColCross.skl")):
        f = ci_pick(ci, src)
        if not f:
            fail("%s: export pool has no %s" % (tag, src))
        shutil.copyfile(os.path.join(export_dir, f),
                        os.path.join(wskl_dir, dst))

    wobj_files = os.listdir(wobj)
    n_obj = sum(1 for f in wobj_files if f.endswith(".obj"))
    log("assemble %s: OBJECTS files %d (%d obj), skeleton dir %d, "
        "rsrcpool files %d (+%d anm aliases), map_Kd pool-fallback refs %d"
        % (tag, len(wobj_files), n_obj, len(os.listdir(wskel)),
           len(os.listdir(wpool)), anm_aliases, sum(tex_fallback.values())))
    return {
        "tag": tag, "tree": tree, "setdir": setdir, "num": num,
        "veh": veh, "bld": bld, "slp": slp,
        "empty": set(empty_kids),
        "blob": blob,
        "export_dir": export_dir,
        "wobj": wobj, "wskel": wskel, "wscripts": wscripts, "wpool": wpool,
        "wmc2res_skeleton": wskl_dir,
        "vp_name": vp_name, "sdf_name": sdf_out_name,
        "tex_fallback": tex_fallback,
    }


