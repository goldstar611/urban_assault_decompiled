def ci_dir_index(path, prefix=""):
    idx = {}
    for root, _dirs, files in os.walk(path):
        for f in files:
            rel = os.path.relpath(os.path.join(root, f), path)
            key = (prefix + "/" + rel.replace(os.sep, "/")).lower() if prefix \
                else rel.replace(os.sep, "/").lower()
            idx.setdefault(key, os.path.join(root, f))
    return idx


def ua_truncate(name):
    """Simulate the FSMgr/uaOpenFile extension truncation (>3 char ext)."""
    pos = name.rfind(".")
    slash = name.rfind("/")
    if pos > slash + 1:
        ext = name[pos + 1:]
        if len(ext) > 3:
            return name[:pos + 4]
    return name


def validate_set(info):
    tag = info["tag"]
    errors = []
    stats = {"ok": 0, "total": 0}

    def check(cond, what):
        stats["total"] += 1
        if cond:
            stats["ok"] += 1
        else:
            errors.append(what)

    wobj_idx = ci_dir_index(info["wobj"])
    wskel_idx = ci_dir_index(info["wskel"], prefix="skeleton")
    wpool_idx = ci_dir_index(info["wpool"])

    all_kids = info["veh"] + info["bld"] + info["slp"]
    for name in all_kids:
        check((name + ".obj").lower() in wobj_idx,
              "%s: missing %s.obj" % (tag, name))
        if name in info["empty"]:
            continue
        check((name + ".uattach").lower() in wobj_idx,
              "%s: missing %s.uattach" % (tag, name))
        uaf = wobj_idx.get((name + ".uattach").lower())
        if not uaf:
            continue
        with open(os.path.join(info["wobj"], uaf), "r") as fh:
            j = json.load(fh)
        skl = j.get("skeleton", "")
        check(skl.lower() in wobj_idx,
              "%s: uattach skeleton missing %s" % (tag, skl))
        for att in j.get("attachments", []):
            f = att.get("file", "")
            check(f.lower() in wobj_idx,
                  "%s: attachment missing %s" % (tag, f))
            for key in ("bmpanim", "bmpanim_tracy"):
                b = att.get(key)
                if isinstance(b, dict) and b.get("file"):
                    check(b["file"].lower() in wobj_idx,
                          "%s: bmpanim missing %s" % (tag, b["file"]))
            for t in att.get("orig_textures") or []:
                have = (name + "_" + t + ".png").lower() in wobj_idx
                if not have:
                    have = (t + ".png").lower() in wpool_idx
                check(have, "%s: texture png missing for '%s' (per-model "
                            "and pool)" % (tag, t))
        for k, v in (j.get("anm_textures") or {}).items():
            check(v.lower() in wobj_idx,
                  "%s: anm texture missing %s" % (tag, v))

    # scripts references (extension truncation simulated via ua_truncate)
    wscripts = info["wscripts"]
    entries, _raw = parse_lst_entries(os.path.join(wscripts, info["vp_name"]))
    check(len(entries) == len(info["veh"]),
          "%s: visproto.lst entries %d != %d vehicle kids"
          % (tag, len(entries), len(info["veh"])))
    for e in entries:
        check(ua_truncate("objects/" + e).lower() in
              {"objects/" + f for f in wobj_idx},
              "%s: visproto ref missing %s" % (tag, e))

    lego_lines, _after = parse_sdf_lego(os.path.join(wscripts,
                                                     info["sdf_name"]))
    sdf_veh = [ln for ln in lego_lines if ln.strip() and not ln.startswith(">")]
    check(len(sdf_veh) == len(info["bld"]),
          "%s: set.sdf lego lines %d != %d building kids"
          % (tag, len(sdf_veh), len(info["bld"])))
    for line in sdf_veh:
        toks = re.split(r"[;#]", line)[0].split()
        if len(toks) < 2:
            check(False, "%s: bad sdf line %r" % (tag, line))
            continue
        col1, col2 = toks[0], toks[1]
        check(col1.lower().endswith(".obj"),
              "%s: sdf col1 not .obj: %s" % (tag, col1))
        check(ua_truncate("objects/" + col1).lower() in
              {"objects/" + f for f in wobj_idx},
              "%s: sdf col1 ref missing %s" % (tag, col1))
        check(col2.lower().endswith(".skl"),
              "%s: sdf col2 not .skl: %s" % (tag, col2))
        check(ua_truncate(col2).lower() in wskel_idx,
              "%s: sdf col2 ref missing %s" % (tag, col2))

    slurp_entries, _raw = parse_lst_entries(os.path.join(wscripts,
                                                         "slurps.lst"))
    check(len(slurp_entries) == len(info["slp"]),
          "%s: slurps.lst entries %d != %d slurp kids"
          % (tag, len(slurp_entries), len(info["slp"])))
    for e in slurp_entries:
        check(ua_truncate("objects/" + e).lower() in
              {"objects/" + f for f in wobj_idx},
              "%s: slurps ref missing %s" % (tag, e))

    # rsrcpool: every blob VANM name must resolve
    vanm_names = load_blob_pool_names(info["blob"]).get("VANM", [])
    for e in vanm_names:
        stem = strip_suffix(e, ".anm")
        have = (stem + ".anm").lower() in wpool_idx or e.lower() in wpool_idx
        check(have, "%s: rsrcpool anm missing for '%s'" % (tag, e))
    check(len(wpool_idx) > 0, "%s: rsrcpool empty" % tag)

    # MC2RES/Skeleton
    for f in ("ColSide.skl", "ColCross.skl"):
        check(os.path.isfile(os.path.join(info["wmc2res_skeleton"], f)),
              "%s: missing MC2RES/Skeleton/%s" % (tag, f))

    # no SET.BAS may exist in the converted OBJECTS dir
    check(not any(f.upper() == "SET.BAS" for f in os.listdir(info["wobj"])),
          "%s: SET.BAS present in OBJECTS" % tag)

    return stats["ok"], stats["total"], errors


