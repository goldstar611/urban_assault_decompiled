def copy_work(package, work):
    if os.path.exists(work):
        log("work copy: %s exists, updating (movies/audio/SET.BAS excluded)"
            % work)
    else:
        log("work copy: creating %s" % work)
    os.makedirs(work, exist_ok=True)

    def ignore(dirpath, names):
        rel = os.path.relpath(dirpath, package).replace(os.sep, "/")
        out = []
        for n in names:
            r = n if rel == "." else rel + "/" + n
            if r.lower() in EXCLUDE_DIRS_LOWER:
                out.append(n)
                continue
            m = re.fullmatch(
                r"(DATA|dataxp)/(?:SET|Set)(\d+)/"
                r"(?:OBJECTS|Objects|objects)/SET\.BAS",
                r, re.IGNORECASE)
            if m and int(m.group(2)) != 46:
                out.append(n)  # per-set SET.BAS blob: not copied (documented)
        return out

    for entry in os.listdir(package):
        src = os.path.join(package, entry)
        if os.path.isdir(src):
            shutil.copytree(src, os.path.join(work, entry),
                            ignore=ignore, dirs_exist_ok=True)
        else:
            shutil.copy2(src, os.path.join(work, entry))
    leftovers = []
    for tree in ("DATA", "dataxp"):
        troot = os.path.join(work, tree)
        if not os.path.isdir(troot):
            continue
        for dirpath, _dirs, filenames in os.walk(troot):
            for fn in filenames:
                if fn.upper() == "SET.BAS":
                    leftovers.append(
                        os.path.relpath(os.path.join(dirpath, fn), work))
    log("work copy: done (SET.BAS blobs still present: %s)"
        % (", ".join(leftovers) if leftovers else "none"))


