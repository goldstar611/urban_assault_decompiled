def find_set_dirs(package, tree):
    """Return [(dirname, set_number)] for in-scope set dirs of one tree."""
    root = os.path.join(package, tree)
    if not os.path.isdir(root):
        fail("missing tree dir: %s" % root)
    out = []
    for entry in os.listdir(root):
        m = re.fullmatch(r"(SET|Set)(\d+)", entry)
        if not m or int(m.group(2)) not in SCOPE_NUMBERS:
            continue
        set_dir = os.path.join(root, entry)
        blob = None
        for objdir in ("OBJECTS", "Objects", "objects"):
            for blobname in ("SET.BAS", "set.bas"):
                cand = os.path.join(set_dir, objdir, blobname)
                if os.path.isfile(cand):
                    blob = cand
                    break
            if blob:
                break
        if blob is None:
            log("NOTE: %s/%s has no SET.BAS, skipped" % (tree, entry))
            continue
        out.append((entry, int(m.group(2))))
    out.sort(key=lambda t: t[1])
    return out


def tree_paths(package, tree, setdir):
    """Locate case-exact subpaths of one set dir in the package."""
    base = os.path.join(package, tree, setdir)
    ci = {}
    for e in os.listdir(base):
        ci.setdefault(e.lower(), e)

    def pick(lower, default):
        return ci.get(lower, default)

    objdir = pick("objects", "OBJECTS")
    scriptsdir = pick("scripts", "scripts")
    rsrcpool = pick("rsrcpool", "RSRCPOOL")
    return {
        "base": base,
        "objdir": objdir,
        "scriptsdir": scriptsdir,
        "rsrcpool": rsrcpool,
        "objdir_path": os.path.join(base, objdir),
        "scriptsdir_path": os.path.join(base, scriptsdir),
        "rsrcpool_path": os.path.join(base, rsrcpool),
    }


def find_blob_path(paths):
    d = paths["objdir_path"]
    for name in os.listdir(d):
        if name.lower() == "set.bas":
            return os.path.join(d, name)
    fail("no SET.BAS under %s" % d)


def find_mc2res_dir(work_tree):
    for e in os.listdir(work_tree):
        if e.lower() == "mc2res":
            return os.path.join(work_tree, e)
    fail("no MC2RES dir under %s" % work_tree)


