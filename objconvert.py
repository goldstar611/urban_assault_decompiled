def ci_index(names):
    idx = {}
    for f in names:
        idx.setdefault(f.lower(), f)
    return idx


def ci_pick(idx, want):
    return idx.get(want.lower())


def model_asset_plan(export_dir, ci, name):
    """Authoritative per-model file set for one kid.

    Returns (files, origs, mat_pairs, errors):
      files     - exact export file names to byte-copy (includes .obj)
      origs     - original texture names referenced by the model
      mat_pairs - [(orig_texture, pool_png_name)] from the mat.json
      errors    - problems found in the export dir
    """
    files = set()
    origs = set()
    mat_pairs = []
    errors = []

    obj = ci_pick(ci, name + ".obj")
    if not obj:
        errors.append("missing %s.obj in export" % name)
        return files, origs, mat_pairs, errors
    files.add(obj)

    mtl = ci_pick(ci, name + ".obj.mtl")
    if mtl:
        files.add(mtl)
    else:
        errors.append("missing %s.obj.mtl in export" % name)

    uaf = ci_pick(ci, name + ".uattach")
    uattach = None
    if uaf:
        files.add(uaf)
        try:
            with open(os.path.join(export_dir, uaf), "r") as fh:
                uattach = json.load(fh)
        except Exception as exc:
            errors.append("cannot parse %s.uattach: %s" % (name, exc))
    else:
        errors.append("missing %s.uattach in export" % name)

    if uattach:
        skl = uattach.get("skeleton")
        if skl:
            files.add(skl)
            if not ci_pick(ci, skl):
                errors.append("uattach skeleton missing in export: %s" % skl)
        for att in uattach.get("attachments", []):
            f = att.get("file")
            if f:
                files.add(f)
                if not ci_pick(ci, f):
                    errors.append("attachment file missing in export: %s" % f)
            for key in ("bmpanim", "bmpanim_tracy"):
                b = att.get(key)
                if isinstance(b, dict):
                    bf = b.get("file")
                    if bf:
                        files.add(bf)
                        if not ci_pick(ci, bf):
                            errors.append("bmpanim file missing in export: %s"
                                          % bf)
                    for sh in b.get("sheets") or []:
                        origs.add(sh)
            for t in att.get("orig_textures") or []:
                origs.add(t)
        for k, v in (uattach.get("anm_textures") or {}).items():
            origs.add(k)
            files.add(v)

    mj = ci_pick(ci, name + ".obj.mat.json")
    if mj:
        try:
            with open(os.path.join(export_dir, mj), "r") as fh:
                mats = json.load(fh).get("materials", [])
            for m in mats:
                orig = m.get("orig_texture")
                tex = m.get("texture")
                if orig:
                    origs.add(orig)
                if orig and tex:
                    mat_pairs.append((orig, tex))
        except Exception as exc:
            errors.append("cannot parse %s.obj.mat.json: %s" % (name, exc))

    for t in sorted(origs):
        png = ci_pick(ci, name + "_" + t + ".png")
        if png:
            files.add(png)
    return files, origs, mat_pairs, errors


def split_pool(export_files, per_model_exact):
    """Classify export files into per-model (exact names) and pool files."""
    per_model_lower = {f.lower() for f in per_model_exact}
    pool = defaultdict(list)
    for f in export_files:
        if f.lower() not in per_model_lower:
            ext = os.path.splitext(f)[1].lower()
            pool[ext].append(f)
    return pool


def pool_skl_for_base(pool, all_skls, col2base):
    """Export file holding the serialized SKLT named *col2base*."""
    for f in pool.get(".skl", []):
        if os.path.splitext(f)[0] == col2base:
            return f
    for f in pool.get(".skl", []):
        if os.path.splitext(f)[0].lower() == col2base.lower():
            return f
    for f in sorted(all_skls):
        if os.path.splitext(f)[0].lower().endswith("_" + col2base.lower()):
            return f
    return None


